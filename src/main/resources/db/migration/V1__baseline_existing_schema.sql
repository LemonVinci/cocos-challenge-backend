

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255),
    accountnumber varchar(20)
);

CREATE TABLE instruments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker varchar(10),
    name varchar(255),
    type varchar(10)
);

CREATE TABLE orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrumentid integer REFERENCES instruments (id),
    userid integer REFERENCES users (id),
    size integer,
    price numeric(10, 2),
    type varchar(10),
    side varchar(10),
    status varchar(20),
    datetime timestamp
);

CREATE TABLE marketdata (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrumentid integer REFERENCES instruments (id),
    high numeric(10, 2),
    low numeric(10, 2),
    open numeric(10, 2),
    close numeric(10, 2),
    previousclose numeric(10, 2),
    date date
);
